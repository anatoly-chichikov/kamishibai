//! Select the four productive reverse paradigms from the pinned Ablaut source.
use anyhow::{Context, Result, ensure};
use sha2::{Digest, Sha256};
use std::collections::BTreeSet;
use std::fs;
use std::path::Path;
use std::process::Command;

fn section<'a>(source: &'a str, start: &str, end: &str) -> Result<&'a str> {
    let start = source
        .find(start)
        .with_context(|| format!("missing {start}"))?;
    let after = &source[start..];
    let end = after.find(end).with_context(|| format!("missing {end}"))?;
    Ok(&after[..end])
}

fn reverse(source: &str) -> Result<String> {
    ensure!(
        format!("{:x}", Sha256::digest(source.as_bytes()))
            == "69947f8729efb45fdce35772c3145de4ce80de1d236959b80e5e48c46d69f698",
        "unexpected Ablaut reverse analyzer source"
    );
    let mut selected = String::from(
        "//! Selected from Ablaut 0.11.0 (MIT), generated by tools/reader-models.\nuse crate::{lexicon_lemmas, ord};\n",
    );
    for (start, end) in [
        ("use crate::{conjugate,", "/// Whether the forward engine"),
        ("/// The productive ghost shapes", "fn gle_forms("),
        ("const FR_VOWELS:", "fn ord("),
        ("fn index(lang:", "/// The lemma column"),
        ("const P6:", "const P9:"),
        ("struct Slots(", "        Conjugation::Ces(t) =>"),
        (
            "        Conjugation::Eng(t) =>",
            "        Conjugation::Est(t) =>",
        ),
    ] {
        selected.push_str(section(source, start, end)?);
    }
    selected.push_str("    }\n    s.0\n}\n");
    for (original, replacement) in [
        (
            "#[cfg_attr(feature = \"serde\", derive(serde::Serialize))]\n",
            "",
        ),
        ("pub struct ReverseMatch", "pub(super) struct ReverseMatch"),
        ("pub infinitive: String", "pub(super) infinitive: String"),
        ("pub slots: Vec<String>", "slots: Vec<String>"),
        ("pub fn reverse(", "pub(super) fn reverse("),
        (
            "/// the 1990 French grave-accent future), and Irish emits the bare\n/// analytic bases (chuaigh) that the display table only shows glued\n/// to a pronoun.",
            "/// and the 1990 French grave-accent future).",
        ),
        ("        Lang::Gle => gle_forms(lemma),\n", ""),
        (
            "_ => conjugate(lemma, lang).ok().map",
            "Lang::Eng => conjugate(lemma, lang).map",
        ),
        (
            "conjugate(lemma, Lang::Deu).ok()?",
            "conjugate(lemma, Lang::Deu)?",
        ),
        ("use crate::fra::", "use ablaut::fra::"),
        ("use crate::spa::", "use ablaut::spa::"),
        ("        _ => {}\n    }\n    set", "    }\n    set"),
        ("; 59]", "; 4]"),
    ] {
        ensure!(
            selected.contains(original),
            "missing Ablaut selection {original}"
        );
        selected = selected.replace(original, replacement);
    }
    let lines: Vec<_> = selected
        .lines()
        .filter(|line| {
            let trimmed = line.trim_start();
            !trimmed.starts_with("//") || trimmed.starts_with("///") || trimmed.starts_with("//!")
        })
        .map(|line| line.split_once(" // ").map_or(line, |(code, _)| code))
        .collect();
    Ok(lines.join("\n") + "\n")
}

fn lemmas(source: &Path, language: &str) -> Result<String> {
    let mut words = BTreeSet::new();
    let mut files = vec!["verbs.tsv"];
    if language == "spa" {
        files.push("classes.tsv");
    }
    if language == "deu" {
        words.extend(["sein", "werden", "tun"].map(str::to_owned));
    }
    for file in files {
        for line in fs::read_to_string(source.join("data").join(language).join(file))?.lines() {
            let word = line.split('\t').next().unwrap_or("").trim();
            if !line.starts_with('#')
                && !word.is_empty()
                && !word.contains(char::is_whitespace)
                && !word.contains(['\'', '’'])
            {
                words.insert(word.to_owned());
            }
        }
    }
    Ok(words.into_iter().map(|word| word + "\n").collect())
}

/// Reproduce the selected analyzer, its four lexicons, and their upstream license.
pub(super) fn pack(registry: &Path, out: &Path) -> Result<()> {
    let source = registry.join("ablaut-0.11.0");
    let words = out.join("src/lemmas");
    fs::create_dir_all(&words)?;
    for code in ["deu", "eng", "fra", "spa"] {
        fs::write(words.join(format!("{code}.txt")), lemmas(&source, code)?)?;
    }
    fs::copy(source.join("LICENSE-MIT"), out.join("LICENSE"))?;
    let path = out.join("src/reverse.rs");
    fs::write(
        &path,
        reverse(&fs::read_to_string(source.join("src/reverse.rs"))?)?,
    )?;
    ensure!(
        Command::new("rustfmt")
            .args(["--edition", "2021"])
            .arg(path)
            .status()?
            .success(),
        "rustfmt failed for the selected analyzer"
    );
    Ok(())
}
